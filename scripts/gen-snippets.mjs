// Highlights the usage-page snippets with Shiki at build time and writes
// src/usage/snippets.js. Running here rather than in the browser keeps Shiki
// (and its grammars, several MB) out of the bundle entirely.
//
// The snippets are authored in this file and land in a .js module rather than
// the page's own <script> block, for two reasons the page cannot work around:
// a literal </script> inside an embedded string truncates the compiler's
// script-extraction pass, and its import-stripping pass is a blind text
// replace that would mangle any module statement shown as example code.
import { writeFile } from "node:fs/promises";
import { bundledThemes, codeToHtml } from "shiki";

// The one knob for syntax colours, matching olum-ui. Every span carries both
// palettes as --shiki-light/--shiki-dark custom properties (defaultColor:
// false), so the pair is baked into the generated HTML -- rerun
// `npm run snippets` after editing it. main.css picks the side to show.
const THEMES = {
  light: process.env.SHIKI_LIGHT || "min-light",
  dark: process.env.SHIKI_DARK || "material-theme-palenight",
};

// A typo would otherwise surface as an opaque Shiki resolve error mid-run.
for (const [mode, name] of Object.entries(THEMES)) {
  if (!(name in bundledThemes)) throw new Error(`unknown Shiki theme "${name}" for ${mode} mode`);
}

const line = `import { Trash } from "olum-icons/lucide";`;

// One line per package manager, behind a switcher of their own -- same command,
// different spelling.
const INSTALL = {
  npm: `npm i olum-icons`,
  pnpm: `pnpm add olum-icons`,
  yarn: `yarn add olum-icons`,
  bun: `bun add olum-icons`,
};

// Standalone blocks -- sequential steps, so each gets its own panel. `lang`
// doubles as the label shown in the header, so it has to be a real Shiki
// language id.
const SNIPPETS = {
  module: {
    lang: "js",
    code: `${line}

// Trash is a plain SVG string
console.log(Trash); // '<svg xmlns="http://www.w3.org/2000/svg" height="24" ...>'`,
  },
};

// The same icon rendered the idiomatic way in each framework. These are
// alternatives rather than steps, so the page shows them in one panel behind
// tabs -- see CodeTabs.html.
const FRAMEWORKS = [
  {
    id: "olum",
    label: "Olum",
    lang: "html",
    code: `<script>
  ${line}
</script>

<span html="Trash"></span>`,
  },
  {
    id: "svelte",
    label: "Svelte",
    lang: "svelte",
    code: `<script>
  ${line}
</script>

<span>{@html Trash}</span>`,
  },
  {
    id: "vue",
    label: "Vue",
    lang: "vue",
    code: `<script setup>
${line}
</script>

<template>
  <span v-html="Trash"></span>
</template>`,
  },
  {
    id: "react",
    label: "React",
    lang: "jsx",
    code: `${line}

export default function App() {
  return <span dangerouslySetInnerHTML={{ __html: Trash }} />;
}`,
  },
];

const jsString = (value) => "`" + value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";

const highlight = async ({ lang, code }) => {
  const html = await codeToHtml(code, { lang, themes: THEMES, defaultColor: false });

  // A one-line snippet gets no gutter -- a lone "1" next to `npm i olum-icons`
  // is noise. The class rides on Shiki's own <pre>; main.css reads it.
  return code.trim().split("\n").length === 1 ? html.replace(/class="shiki/, 'class="shiki no-lines') : html;
};

const install = [];
for (const [manager, code] of Object.entries(INSTALL)) {
  const html = await highlight({ lang: "bash", code });
  install.push(`  ${JSON.stringify(manager)}: { code: ${jsString(code)}, html: ${jsString(html)} },`);
}

const blocks = [];
for (const [key, snippet] of Object.entries(SNIPPETS)) {
  const html = await highlight(snippet);
  blocks.push(
    `  ${JSON.stringify(key)}: { label: ${JSON.stringify(snippet.label || snippet.lang)}, code: ${jsString(snippet.code)}, html: ${jsString(html)} },`
  );
}

const tabs = [];
for (const fw of FRAMEWORKS) {
  const html = await highlight(fw);
  tabs.push(`  { id: ${JSON.stringify(fw.id)}, label: ${JSON.stringify(fw.label)}, code: ${jsString(fw.code)}, html: ${jsString(html)} },`);
}

const out = [
  "// Generated by scripts/gen-snippets.mjs -- do not edit.",
  "export const install = {",
  ...install,
  "};",
  "",
  "export const snippets = {",
  ...blocks,
  "};",
  "",
  "export const frameworks = [",
  ...tabs,
  "];",
  "",
].join("\n");

await writeFile("src/usage/snippets.js", out);

console.log(`snippets: ${install.length} install command(s) + ${blocks.length} block(s) + ${tabs.length} framework tab(s) -> src/usage/snippets.js`);
